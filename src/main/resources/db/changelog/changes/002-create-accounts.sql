CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  owner_id BIGINT NOT NULL,
  account_number VARCHAR(34) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  balance NUMERIC(19, 4) NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  
  CONSTRAINT pk_accounts PRIMARY KEY (id),
  CONSTRAINT uq_accounts_account_number UNIQUE (account_number),
  CONSTRAINT fk_accounts_owner
  FOREIGN KEY (owner_id)
  REFERENCES users (id)
  ON DELETE RESTRICT,
  CONSTRAINT uq_accounts_id_currency UNIQUE (id, currency),
  CONSTRAINT chk_account_balance_nonnegative CHECK (balance >= 0),
  CONSTRAINT chk_accounts_status CHECK (status IN ('ACTIVE', 'BLOCKED')),
  CONSTRAINT chk_accounts_currency CHECK (currency ~ '^[A-Z]{3}$')
);

COMMENT ON TABLE accounts IS 'Банковские счета';

