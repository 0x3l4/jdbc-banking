CREATE TABLE ledger_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  transfer_id UUID NOT NULL,
  account_id BIGINT NOT NULL,
  amount NUMERIC(19, 4) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  CONSTRAINT pk_ledger_entries
  PRIMARY KEY (id),
  
  CONSTRAINT fk_ledger_entries_transfer
  FOREIGN KEY (transfer_id)
  REFERENCES transfers (id)
  ON DELETE RESTRICT,
  
  CONSTRAINT fk_ledger_entries_account
  FOREIGN KEY (account_id)
  REFERENCES accounts (id)
  ON DELETE RESTRICT,
  
  CONSTRAINT uq_ledger_entries_transfer_account
  UNIQUE (transfer_id, account_id),
  
  CONSTRAINT chk_nonzero_amount
  CHECK (amount <> 0)
);

COMMENT ON TABLE ledger_entries IS 'Денежные проводки';

